// Helper: return a complete <svg> string for an icon name.
//   opts: {size: number=16, cls: string='', stroke: number=1.6, fillBg: bool=false}
function _renderIcon(name, opts){
  const path = _ICON_PATHS[name];
  if(!path){
    // Soft fallback: render an empty box so layout doesn't break
    return '<svg width="' + (opts && opts.size || 16) + '" height="' + (opts && opts.size || 16) + '" viewBox="0 0 24 24" aria-hidden="true"></svg>';
  }
  const size = (opts && opts.size) || 16;
  const cls  = (opts && opts.cls)  || '';
  const stroke = (opts && opts.stroke) || 1.6;
  return '<svg width="' + size + '" height="' + size + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="' + stroke + '" stroke-linecap="round" stroke-linejoin="round" class="icon ' + cls + '" aria-hidden="true">' + path + '</svg>';
}

